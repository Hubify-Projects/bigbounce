#        four-fermion operator built from the SAME psi field => SAME kappa
#        = M_Pl^{-2} power (Fierz mixes classes with O(1) rational coefficients,
#        never changes the number of fields or the coupling dimension);
#      * parity-relevant Lorentz scalars are exactly {SS,PP,VV,AA,TT,VA,SP}.
# ----------------------------------------------------------------------------
produced_AA = {classes[i] for i in range(5) if outAA[i] != 0}
enumerated = {"S", "V", "T", "A", "P"}
escape = produced_AA - enumerated
print("\n[9] CLOSURE VERDICT")
print(f"      AA Fierz-produces classes: {sorted(produced_AA)}")
print(f"      enumerated dim-6 basis   : {sorted(enumerated)}")
