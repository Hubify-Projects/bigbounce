# so the kappa=M_Pl^-2 prefactor is untouched. Confirm all F entries are rational.
all_rational = all(F[i, j].is_rational for i in range(5) for j in range(5))
print(f"      all Fierz coefficients dimensionless rationals "
      f"(kappa power preserved): {all_rational}")

