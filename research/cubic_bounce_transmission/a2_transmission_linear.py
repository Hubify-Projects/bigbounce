def _matter_basis(k, tau):
    u = k * tau
    S = np.sin(u) / u - np.cos(u)
    C = np.cos(u) / u + np.sin(u)
    dS = k * (np.cos(u) / u - np.sin(u) / u**2 + np.sin(u))
    dC = k * (-np.sin(u) / u - np.cos(u) / u**2 + np.cos(u))
    return S, C, dS, dC


def project(bg, k, eta_m, mu, dmu):
    """(mu, mu') -> (alpha, beta) in the normalisation zeta_C -> 1,
    zeta_G -> -1/(3 A^2 tau^3)  (so mu_G = -1/(3 A tau));
    alpha = C1 -+ C2 I_inf (pre/post), beta = C2."""
    A, off = bg["A"], bg["eta_off"]
    tau = eta_m - off
    S, C, dS, dC = _matter_basis(k, tau)
    mC, dmC = (3 * A / k**2) * S, (3 * A / k**2) * dS
    mG, dmG = -(k / (3 * A)) * C, -(k / (3 * A)) * dC
    W = mC * dmG - dmC * mG
    return (mu * dmG - dmu * mG) / W, (mC * dmu - dmC * mu) / W


def _rhs_factory(spl, k):
    def rhs(e, y):
        w = spl(e)
        return [y[1], -(k * k - w) * y[0], y[3], -(k * k - w) * y[2]]
    return rhs


def evolve(bg, k, eta_far, ic="vacuum", rtol=1e-11, atol=1e-14):
    spl = CubicSpline(bg["eta"], bg["appa"])
    off = bg["eta_off"]
    e_i, e_f = -eta_far, eta_far
    tau_i = e_i - off
    if ic == "vacuum":
        u = k * tau_i
        mu0 = np.exp(-1j * u) * (1 - 1j / u) / np.sqrt(2 * k)
        dmu0 = (np.exp(-1j * u) * (-1j * k) * (1 - 1j / u)
                + np.exp(-1j * u) * (1j / (k * tau_i**2))) / np.sqrt(2 * k)
    else:
        raise ValueError(ic)
    sol = solve_ivp(_rhs_factory(spl, k), [e_i, e_f],
                    [mu0.real, dmu0.real, mu0.imag, dmu0.imag],
                    rtol=rtol, atol=atol, method="DOP853", dense_output=True)
    yf = sol.y[:, -1]
    mu_f, dmu_f = yf[0] + 1j * yf[2], yf[1] + 1j * yf[3]
    a_m, b_m = project(bg, k, e_i, mu0, dmu0)
    a_p, b_p = project(bg, k, e_f, mu_f, dmu_f)
    return {"alpha_pre": a_m, "beta_pre": b_m, "alpha_post": a_p, "beta_post": b_p,
            "sol": sol, "eta_i": e_i, "eta_f": e_f, "success": bool(sol.success)}


def constant_branch_transmission(bg, k, u_out=0.2, rtol=1e-12, atol=1e-16):
    r"""Independent reproduction of the phase-3 result T_c(k) = 1.

    At k = 0 the EXACT constant-zeta solution of mu'' = (a''/a) mu is mu = a(eta)
    (zeta = mu/a = 1), for ANY background.  Impose that as the IC at a symmetric
    super-Hubble epoch -eta_out (k eta_out = u_out << 1), integrate the full
    finite-k equation through the bounce, and read zeta = mu/a at +eta_out.
    T_c = zeta(+eta_out)/zeta(-eta_out); any deviation from 1 is the physical
    O((k eta_out)^2) gradient correction plus numerics -- NOT the matter-asymptote
    IC mismatch that contaminates a projected-basis version of this test.
    """
    eta_out = u_out / k
    if eta_out > 0.9 * bg["eta_far"] or eta_out < 3.0 * bg["eta_B"]:
        return None
    spl = CubicSpline(bg["eta"], bg["appa"])
    spa, sf1, sF = bg["af"], bg["f1f"], bg["Ff"]
    # constant branch prepared to O(k^4): zeta_C = 1 + k^2 f1, mu = a zeta_C
    e0 = -eta_out
    a0, ap0 = float(spa(e0)), float(spa.derivative()(e0))
    z0 = 1.0 + k * k * float(sf1(e0))
    dz0 = k * k * (-float(sF(e0)) / a0**2)          # f1' = -F/a^2
    mu0, dmu0 = a0 * z0, ap0 * z0 + a0 * dz0

    def rhs(e, y):
        return [y[1], -(k * k - spl(e)) * y[0]]

    sol = solve_ivp(rhs, [e0, eta_out], [mu0, dmu0], rtol=rtol, atol=atol, method="DOP853")
    z_out = sol.y[0, -1] / float(spa(eta_out))
    z_ref = 1.0 + k * k * float(sf1(eta_out))       # zeta_C(+eta_out) (f1 even by parity)
    Tc = z_out / z_ref
    return {"k": float(k), "k_etaB": float(k * bg["eta_B"]), "eta_out": float(eta_out),
            "eta_out_over_etaB": float(eta_out / bg["eta_B"]), "u_out": float(u_out),
            "k2_f1_correction": float(k * k * float(sf1(eta_out))),
            "T_c": float(Tc), "abs_T_c_minus_1": float(abs(Tc - 1.0))}


def zeta_at(bg, ev, eta_q):
    """zeta = mu/a from the dense ODE solution."""
    y = ev["sol"].sol(eta_q)
    mu = y[0] + 1j * y[2]
    return mu / np.interp(eta_q, bg["eta"], bg["a"])


