def _finalize(eta, a, appa, Hdot, J, label, params):
    """eta, a, appa, Hdot, J given on the full line (J(0) = 0). Derive eta_B,
    I_inf, matter fit A/eta_off."""
    I_inf = float(J[-1])
    # eta_B: first zero of Hdot at eta > 0 (edge of the NEC-violation window)
    sH = CubicSpline(eta, Hdot)
    ib = int(np.argmin(np.abs(eta)))
    i = ib
    while i + 1 < len(eta) and Hdot[i + 1] > 0:
        i += 1
    eta_B = float(brentq(sH, eta[i], eta[i + 1])) if i + 1 < len(eta) else float(eta[-1])
    # matter fit: sqrt(a) linear in eta over the far tail (a > 0.3 a_max)
    m = a > 0.3 * a[-1]
    m &= eta > 0
    e_t, s_t = eta[m], np.sqrt(a[m])
    slope, icept = np.polyfit(e_t, s_t, 1)
    A = float(slope**2)
    eta_off = float(-icept / slope)
    sJ = CubicSpline(eta, J)
    # Weinberg gradient-expansion O(k^2) correction to the constant branch:
    #   zeta_C(eta) = 1 + k^2 f1(eta) + O(k^4),
    #   F(eta) = int_0^eta a^2 deta',   f1(eta) = -int_0^eta F/a^2 deta'
    F = np.concatenate([[0.0], cumulative_trapezoid(a**2, eta)])
    F = F - float(np.interp(0.0, eta, F))
    f1 = np.concatenate([[0.0], cumulative_trapezoid(-F / a**2, eta)])
    f1 = f1 - float(np.interp(0.0, eta, f1))
    return {"label": label, "params": params, "eta": eta, "a": a, "appa": appa,
            "J": J, "Jf": sJ, "I_inf": I_inf, "eta_B": eta_B, "A": A, "eta_off": eta_off,
            "J_at_minus_etaB": float(sJ(-eta_B)), "eta_far": float(eta[-1]),
            "matter_fit_npts": int(m.sum()),
            "af": CubicSpline(eta, a), "f1f": CubicSpline(eta, f1),
            "Ff": CubicSpline(eta, F)}


def _mirror(eta_h, a_h, appa_h, Hd_h, J_h):
    eta = np.concatenate([-eta_h[::-1][:-1], eta_h])
    a = np.concatenate([a_h[::-1][:-1], a_h])
    appa = np.concatenate([appa_h[::-1][:-1], appa_h])
    Hd = np.concatenate([Hd_h[::-1][:-1], Hd_h])
    J = np.concatenate([-J_h[::-1][:-1], J_h])
    return eta, a, appa, Hd, J


def bg_lqc(x_min=1e-12, N1=200001, N2=200001, x_split=0.1):
    """(i) LQC effective quasi-dust bounce, H^2 = (rho/3)(1 - rho/rho_c), w = 0.
    Two-piece parametrization: s = sqrt(1-x) through the bounce (regular, no
    regulator), y = ln x through the matter tail (resolves a -> inf)."""
    # piece A: bounce region x in [x_split, 1]
    s1 = np.sqrt(1.0 - x_split)
    s = np.linspace(0.0, s1, N1)
    xA = 1.0 - s**2
    detaA = 2.0 / (np.sqrt(3.0) * (1.0 - s**2) ** (7.0 / 6.0))
    dJA = 2.0 / (np.sqrt(3.0) * np.sqrt(1.0 - s**2))
    etaA = np.concatenate([[0.0], cumulative_trapezoid(detaA, s)])
    JA = np.concatenate([[0.0], cumulative_trapezoid(dJA, s)])
    # piece B: matter tail x in [x_min, x_split], y = ln x descending
    y = np.linspace(np.log(x_split), np.log(x_min), N2)
    xB = np.exp(y)
    detaB = -xB ** (-1.0 / 6.0) / (np.sqrt(3.0) * np.sqrt(1.0 - xB))
    dJB = -np.sqrt(xB) / (np.sqrt(3.0) * np.sqrt(1.0 - xB))
    etaB_ = etaA[-1] + np.concatenate([[0.0], cumulative_trapezoid(detaB, y)])
    JB_ = JA[-1] + np.concatenate([[0.0], cumulative_trapezoid(dJB, y)])
    x = np.concatenate([xA, xB[1:]])
    eta_h = np.concatenate([etaA, etaB_[1:]])
    J_h = np.concatenate([JA, JB_[1:]])
    a_h = x ** (-1.0 / 3.0)
    appa_h = x ** (1.0 / 3.0) * (1.0 / 6.0 + x / 3.0)   # a''/a, phase-2 result
    Hd_h = -0.5 * x * (1.0 - 2.0 * x)                   # LQC Hdot; > 0 for x > 1/2
    return _finalize(*_mirror(eta_h, a_h, appa_h, Hd_h, J_h),
                     "LQC-effective-dust", {"rho_c": 1.0, "w": 0.0, "x_min": x_min})


def bg_poly(eta_b=1.0, u_far=4000.0, N=400001):
    """(ii) analytic non-LQC bounce a(eta) = a_b (1 + eta^2/eta_b^2), a_b = 1.
    Everything closed form: a''/a = 2/(eta^2+eta_b^2); J = (eta_b/2)[atan u + u/(1+u^2)];
    I_inf = pi eta_b/4; Hdot = 0 at u = 1/sqrt(3)."""
    u = np.linspace(-u_far, u_far, N)
    eta = u * eta_b
    a = 1.0 + u**2
    appa = 2.0 / (eta_b**2 * (1.0 + u**2))
    Hd = (2.0 / eta_b**2) * (1.0 - 3.0 * u**2) / (1.0 + u**2) ** 4
    J = 0.5 * eta_b * (np.arctan(u) + u / (1.0 + u**2))
    return _finalize(eta, a, appa, Hd, J, "poly-analytic-nonLQC",
                     {"eta_b": eta_b, "a_b": 1.0})


def bg_quintin(dtB=1.0, t_far=1.0e6, N=400001):
    """(iii) Quintin, Sherkatghanad, Cai & Brandenberger 2015 (arXiv:1508.04141):
    bounce phase H(t) = Upsilon (t - t_B), a = a_B exp(Upsilon (t-t_B)^2/2),
    matched to matter contraction/expansion at the NEC boundary |t - t_B| = dtB/2.
    Matching H fixes Upsilon = 8/(3 dtB^2); a_B = 1, t_B = 0."""
    Ups = 8.0 / (3.0 * dtB**2)
    tm = dtB / 2.0
    aB = 1.0
    a_m = aB * np.exp(Ups * tm**2 / 2.0)
    n_in, n_out = N // 2, N // 2
    t_in = np.linspace(0.0, tm, n_in)
    t_out = tm * np.exp(np.linspace(0.0, np.log(t_far / tm), n_out))[1:]
    t = np.concatenate([t_in, t_out])
    inb = t <= tm
    a = np.where(inb, aB * np.exp(Ups * np.minimum(t, tm) ** 2 / 2.0),
                 a_m * (np.maximum(t, tm) / tm) ** (2.0 / 3.0))
    H = np.where(inb, Ups * t, (2.0 / 3.0) / np.maximum(t, tm))
    Hd = np.where(inb, Ups, -1.5 * H**2)
    eta_h = np.concatenate([[0.0], cumulative_trapezoid(1.0 / a, t)])
    J_h = np.concatenate([[0.0], cumulative_trapezoid(1.0 / a**3, t)])
    appa_h = a**2 * (2.0 * H**2 + Hd)
    return _finalize(*_mirror(eta_h, a, appa_h, Hd, J_h),
                     "Quintin2015-type", {"dtB": dtB, "Upsilon": Ups, "a_B": aB,
                                          "t_far": t_far})


