def T_fNL_background(bg, eta_h):
    """large-|r| (background-only) value: T = (1 - rho)/2."""
    rho = abs(float(bg["Jf"](-eta_h))) / bg["I_inf"]
    return rho, 0.5 * (1.0 - rho)


def T_fNL_exact(bg, k, eta_h, ev):
    """exact finite-k value from the projected vacuum coefficients."""
    am, bm = ev["alpha_pre"], ev["beta_pre"]
    C1, C2 = am + bm * bg["I_inf"], bm
    Jh = float(bg["Jf"](-eta_h))
    lam = (C1 + C2 * bg["I_inf"]) / (C1 + C2 * Jh)
    return 1.0 / lam


