def symbolic_block():
    u = sp.symbols("u", positive=True)
    S = sp.sin(u) / u - sp.cos(u)
    C = sp.cos(u) / u + sp.sin(u)
    resS = sp.simplify(sp.diff(S, u, 2) + (1 - 2 / u**2) * S)
    resC = sp.simplify(sp.diff(C, u, 2) + (1 - 2 / u**2) * C)
    S_lead = sp.simplify(sp.series(S, u, 0, 3).removeO())    # ~ u^2/3 -> zeta const
    C_lead = sp.simplify(sp.series(C, u, 0, 2).removeO())    # ~ 1/u   -> zeta ~ tau^-3
    # identity [S1]: e^{-iu}(1 - i/u) + S + i C == 0
    ident_expr = sp.exp(-sp.I * u) * (1 - sp.I / u) + S + sp.I * C
    ident = sp.simplify(sp.expand(ident_expr.rewrite(sp.cos)))
    W = sp.simplify(S * sp.diff(C, u) - sp.diff(S, u) * C)
    A, k, Iinf, rho = sp.symbols("A k I_inf rho", positive=True)
    alpha_m = -k**2 / (3 * A * sp.sqrt(2 * k))
    beta_m = sp.I * 3 * A / (k * sp.sqrt(2 * k))
    r = sp.simplify(beta_m * Iinf / alpha_m)                 # = -9 i A^2 I_inf/k^3
    rr = sp.symbols("r")
    T = (1 + rr * (1 - rho)) / (1 + 2 * rr)
    T_lim = sp.simplify(sp.limit(T, rr, sp.oo))
    return {
        "S_solves_matter_eq": bool(resS == 0),
        "C_solves_matter_eq": bool(resC == 0),
        "S_small_u": str(S_lead),
        "C_small_u": str(C_lead),
        "identity_expmiu_eq_minusS_minusiC": bool(ident == 0),
        "wronskian_S_C": str(W),
        "alpha_minus": str(alpha_m),
        "beta_minus": str(beta_m),
        "r_beta_Iinf_over_alpha": str(r),
        "T_fNL_exact": "(1 + r(1 - rho))/(1 + 2 r)",
        "T_fNL_large_r_limit": str(T_lim),
        "note": ("the adiabatic vacuum in matter contraction is GROWING-branch dominated, "
                 "|r| = 9 A^2 I_inf/k^3 >> 1 for k eta_B << 1; hence T_fNL -> (1-rho)/2 "
                 "and 0 < T_fNL <= 1/2 for ANY bounce of this class"),
    }


