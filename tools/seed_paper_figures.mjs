/**
 * Seed `paper_figures` rows for the 6 bigbounce papers by parsing each
 * paper's current .tex file for \includegraphics{...} and the surrounding
 * \caption{...} + \label{...} blocks.
 *
 * For each figure:
 *   1. Pull the basename from \includegraphics
 *   2. Resolve a public asset path under site/public/ (probes a list of
 *      known mirror locations; falls back to the paper-local figures/ dir
 *      if a copy lives at site/public/images/<basename>.png)
 *   3. Extract the nearest \caption{...} and \label{fig:...} (paren-balanced)
 *   4. Upsert into Convex paper_figures via figures:upsertByOrdinal
 *
 * Stale figures are pruned by calling figures:removeByPaper before each
 * paper's upsert wave, so figures removed from the .tex in a revision
 * round disappear automatically.
 *
 * Idempotent. Safe to re-run.
 */
